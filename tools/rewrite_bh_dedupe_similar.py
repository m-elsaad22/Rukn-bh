def city_hook_html(city: str, verb: str, fam: str, n: int) -> str:
    """City-true blocks so same-service pages do not collapse after city-name stripping."""
    info = CITIES[city]
    log = fx.LOG[city]
    areas = info["areas"]
    a0, a1, a2 = areas[0], areas[min(1, len(areas) - 1)], areas[-1]
    n0 = AREA_NOTES.get(a0, log["pick"])
    n1 = AREA_NOTES.get(a1, log["watch"])
    n2 = AREA_NOTES.get(a2, log["route"])
    stories = CITY_STORIES[city]
    rot = stories[n % 3 :] + stories[: n % 3]
    chunks = [
        f"<h2>{verb} في {a0} و{a1}: فرق المدخل لا فرق الاسم</h2>"
        f"<p>{info['housing']} لذلك عدة {verb} في {city} تُختار بعد وصف المدخل لا بعد نسخ صفحة مدينة أخرى. {info['access']}</p>"
        f"<p>{info['climate']} {info['season']}</p>"
        f"<p>في {a0}: {n0} في {a1}: {n1} أما {a2}: {n2}</p>"
        f"<p>{info['risk']} {info['note']} هذا يخص {verb} داخل {city} — عائلة {fam}.</p>"
        f"<p>{log['pick']} {log['watch']} {log['route']}</p>"
    ]
    for title, body in rot:
        chunks.append(f"<h2>{title}</h2><p>{body}</p>")
    return "".join(chunks)


def targets_from(posts: list) -> list:
    out = []
    for p in posts:
        slug = p.get("slug") or ""
        if fx.family_of(slug) in ONLY:
            out.append(p)
    return out


def update_one(post: dict, by_svc, by_city, by_fam, meta) -> tuple:
    pid = post["id"]
    title = title_of(post)
    slug = post.get("slug") or ""
    built = assemble_html(title, slug)
    rec = meta[pid]
    n = seed(rec["title"], rec["slug"], "seo-graph")
    cities, related = pick_links(rec, by_svc, by_city, by_fam, n)
    cur = rec["cats"][0] if rec["cats"] else 14
    tgt = target_cat(rec["svc"])
    new_cat = tgt if cur == 14 and tgt != 14 else cur
    html = inject(built["html"], graph_html(rec, cities, related, new_cat, n))
    tag_ids = [i for i in (fx.ensure_tag(t) for t in built["tags"]) if i]
    payload = {"content": html, "excerpt": built["excerpt"], "title": built["title"]}
    if tag_ids:
        payload["tags"] = tag_ids
    if new_cat != cur:
        payload["categories"] = [new_cat]
    fx.load_city_ids()
    from rewrite_bh_kayan import CITY_IDS, CITY_SLUG

    cid = CITY_IDS.get(built["city"])
    if cid:
        payload["cities"] = [cid]
    payload["meta"] = built["meta"]
    code, out = req("POST", f"/wp/v2/posts/{pid}", payload)
    if code not in (200, 201):
        payload.pop("meta", None)
        code, out = req("POST", f"/wp/v2/posts/{pid}", payload)
        if code not in (200, 201):
            return pid, f"err{code}:{str(out)[:70]}", built["wc"], slug
    slc = CITY_SLUG.get(built["city"])
    if slc:
        fx.cli(f"post term set {pid} cities {slc}", write=True)
    for k, v in built["meta"].items():
        fx.set_meta(pid, k, v)
    return pid, "ok", built["wc"], slug


def _tokens(text: str) -> set[str]:
    return {w for w in re.findall(r"\w{3,}", text) if w}


def assemble_html(title: str, slug: str) -> dict:
    b = fx.build_payload(title, slug)
    n = seed(title, slug, "seo-graph")
    verb = fx.PACKS[b["fam"]]["verb"]
    hook = city_hook_html(b["city"], verb, b["fam"], n)
    html = b["html"]
    if "-YC-FaqsSimple-vsingle" in html:
        html = html.replace('<div class="-YC-FaqsSimple-vsingle">', hook + '\n<div class="-YC-FaqsSimple-vsingle">', 1)
    else:
        html = html.replace("</article>", hook + "</article>", 1)
    vis = visible_text(html)
    words = word_list(html)
    dens = vis.count(b["full"]) / max(len(words), 1)
    pads = [
        f"<p>{b['full']} تُشرح بالصور والعنوان قبل أي رقم.</p>",
        f"<p>مدخل {b['city']} جزء من تنفيذ {b['full']}.</p>",
        f"<p>نطاق {b['full']} يُكتب بعد التفاصيل لا قبلها.</p>",
        f"<p>واتساب يبقى مرجع صور {b['full']} داخل {b['city']}.</p>",
        f"<p>لا نبدأ {b['full']} دون تأكيد المعلم.</p>",
    ]
    j = 0
    while dens < 0.0072 and j < len(pads):
        nxt = (vis.count(b["full"]) + 1) / max(len(words) + 12, 1)
        if nxt > 0.0102:
            break
        html = html.replace("</article>", pads[(n + j) % len(pads)] + "</article>", 1)
        vis = visible_text(html)
        words = word_list(html)
        dens = vis.count(b["full"]) / max(len(words), 1)
        j += 1
    leftover = re.findall(r"\{[a-z_]+\}", html)
    return {
        **b,
        "html": html,
        "wc": len(words),
        "dens": dens,
        "vis": vis,
        "leftover": leftover,
    }


