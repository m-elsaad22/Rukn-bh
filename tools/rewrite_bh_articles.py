def auth() -> str:
    return "Basic " + base64.b64encode(f"{USER}:{PASSWORD}".encode()).decode()


def req(method: str, route: str, payload=None, timeout=120):
    url = f"{BASE}/?rest_route={route}"
    data = None if payload is None else json.dumps(payload, ensure_ascii=False).encode()
    headers = {
        "Authorization": auth(),
        "Accept": "application/json",
        "User-Agent": "Mozilla/5.0 RuknBH-Rewrite/3.0",
    }
    if data:
        headers["Content-Type"] = "application/json"
    request = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(request, timeout=timeout) as resp:
            body = resp.read().decode("utf-8", "replace")
            return resp.status, json.loads(body) if body else {}
    except urllib.error.HTTPError as exc:
        body = exc.read().decode("utf-8", "replace")
        try:
            parsed = json.loads(body)
        except json.JSONDecodeError:
            parsed = {"raw": body[:300]}
        return exc.code, parsed


def parse_title(title: str) -> tuple[str, str]:
    city = ""
    for name in sorted(CITIES, key=len, reverse=True):
        if f"في {name}" in title or title.endswith(name):
            city = name
            break
    service = title
    if city:
        service = re.sub(rf"\s*في\s+{re.escape(city)}\s*$", "", title)
    service = re.sub(r"^(شركة|فني)\s+", "", service).strip()
    return service, city


