def fetch_posts() -> list[dict]:
    posts = []
    page = 1
    while page <= 30:
        code, data = req(
            "GET",
            f"/wp/v2/posts&per_page=100&page={page}&context=edit&status=publish&_fields=id,title,slug",
        )
        if code != 200 or not data:
            break
        posts.extend(data)
        if len(data) < 100:
            break
        page += 1
    return posts


def update_one(post: dict) -> tuple[int, str, int, float]:
    pid = post["id"]
    title = post.get("title", {}).get("raw") or post.get("title", {}).get("rendered") or ""
    slug = post.get("slug") or ""
    html, excerpt = build_article(title, slug)
    words = word_list(html)
    vis = visible_text(html)
    service, city = parse_title(title)
    kw = f"{service} في {city}"
    dens = kw_hits(vis, title, kw) / max(len(words), 1)
    payload = {"content": html, "excerpt": excerpt}
    code, out = req("POST", f"/wp/v2/posts/{pid}", payload)
    if code in (200, 201):
        return pid, "ok", len(words), dens
    return pid, f"err{code}:{str(out)[:80]}", len(words), dens


