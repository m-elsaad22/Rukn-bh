def main() -> int:
    if "--dry-run" in sys.argv:
        sample_report()
        return 0
    if not os.environ.get("WP_APP_PASSWORD"):
        print("WP_APP_PASSWORD missing", file=sys.stderr)
        return 1
    sample_report()
    posts = fetch_targets()
    if "--limit" in sys.argv:
        posts = posts[: int(sys.argv[sys.argv.index("--limit") + 1])]
    print("targets", len(posts), flush=True)
    ok = err = 0
    wmin, dmin = 10**9, 1.0
    with ThreadPoolExecutor(max_workers=5) as pool:
        futs = [pool.submit(update_one, p) for p in posts]
        for i, fut in enumerate(as_completed(futs), 1):
            pid, st, wc, dens, slug = fut.result()
            wmin = min(wmin, wc)
            dmin = min(dmin, dens)
            if st.startswith("ok"):
                ok += 1
            else:
                err += 1
                print("fail", pid, slug, st)
            if i % 20 == 0:
                print(f"progress {i}/{len(posts)} ok={ok} err={err} min_words={wmin} min_dens={dmin:.3%}", flush=True)
    print(f"done ok={ok} err={err} min_words={wmin} min_dens={dmin:.3%}")
    return 0 if err == 0 else 2


