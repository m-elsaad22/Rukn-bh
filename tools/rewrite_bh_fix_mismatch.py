def fetch_targets() -> list[dict]:
    posts = []
    page = 1
    while page <= 20:
        code, data = req("GET", f"/wp/v2/posts&per_page=100&page={page}&status=publish&_fields=id,title,slug")
        if code != 200 or not data:
            break
        posts.extend(data)
        if len(data) < 100:
            break
        page += 1
    out = []
    for p in posts:
        slug = p.get("slug") or ""
        if family_of(slug):
            out.append(p)
    return out


def update_one(post: dict) -> tuple[int, str, int, float, str]:
    pid = post["id"]
    title = (post.get("title") or {}).get("raw") or (post.get("title") or {}).get("rendered") or ""
    title = re.sub(r"<[^>]+>", "", title).strip()
    slug = post.get("slug") or ""
    built = build_payload(title, slug)
    tag_ids = [i for i in (ensure_tag(t) for t in built["tags"]) if i]
    payload = {"content": built["html"], "excerpt": built["excerpt"], "title": built["title"]}
    if tag_ids:
        payload["tags"] = tag_ids
    load_city_ids()
    cid = CITY_IDS.get(built["city"])
    if cid:
        payload["cities"] = [cid]
    payload["meta"] = built["meta"]
    code, out = req("POST", f"/wp/v2/posts/{pid}", payload)
    if code not in (200, 201):
        payload.pop("meta", None)
        code, out = req("POST", f"/wp/v2/posts/{pid}", payload)
        if code not in (200, 201):
            return pid, f"err{code}:{str(out)[:80]}", built["wc"], built["dens"], slug
    slc = CITY_SLUG.get(built["city"])
    if slc:
        cli(f"post term set {pid} cities {slc}", write=True)
    fail = 0
    for k, v in built["meta"].items():
        if not set_meta(pid, k, v):
            fail += 1
    st = "ok" if fail == 0 else f"ok-meta{fail}"
    return pid, st, built["wc"], built["dens"], slug


