def family_of(slug: str) -> str | None:
    for p in PREFIXES:
        if slug == p or slug.startswith(p + "-"):
            return p
    return None


def city_of(title: str, slug: str) -> str:
    _, city = parse_title(title)
    if city in CITIES:
        return city
    for name, sl in CITY_SLUG.items():
        if slug.endswith(sl) or slug.endswith(sl.replace("-", "")):
            return name
    return "المنامة"


def fill(text: str, city: str) -> str:
    info = CITIES[city]
    log = LOG[city]
    return (
        text.replace("{city}", city)
        .replace("{hub}", log["hub"])
        .replace("{pick}", log["pick"])
        .replace("{route}", log["route"])
        .replace("{watch}", log["watch"])
        .replace("{kind}", info["kind"])
        .replace("{housing}", info["housing"])
    )


def hero_block(full: str, city: str, n: int, pack: dict) -> str:
    heads = [
        fill(pack.get("verb", "الخدمة") + " في " + city, city),
        pick(n, ["عرض مكتوب بعد التفاصيل", "مسار واضح قبل الحركة", f"تنفيذ داخل {city}"]),
    ]
    return (
        f'<section class="kayan-hero"><span>ركن التطور — البحرين</span>'
        f"<h2>{heads[n % 2]}</h2>"
        f"<p>{fill(pack['what'], city)}</p>"
        f'<a href="https://wa.me/{WA}"><i class="fa-brands fa-whatsapp"></i> واتساب {full}</a></section>'
    )


